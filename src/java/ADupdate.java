    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try{
    Connection c = DBconnection.getConnection();
    String newPass = String.valueOf(jPasswordField1.getPassword());  
    String confirmPass = String.valueOf(jPasswordField2.getPassword()); 
    String oldPass = String.valueOf(jPasswordField3.getPassword());   
    if (newPass.equals(confirmPass)) {
        String sql = "UPDATE admin SET Passcode=? WHERE userid=? AND Passcode=?";
        PreparedStatement ps = c.prepareStatement(sql);
        ps.setString(1, newPass);                    
        ps.setString(2, jTextField1.getText());       
        ps.setString(3, oldPass);                    
        int rows = ps.executeUpdate();
        if (rows > 0) {
            JOptionPane.showMessageDialog(this, "Password Updated Successfully!");
        } else {
            JOptionPane.showMessageDialog(this, "Invalid User ID or Old Password!");
        }
    } else {
        JOptionPane.showMessageDialog(this, "New Password and Confirm Password do not match!");
    }
        }
        catch(Exception e){
        JOptionPane.showMessageDialog(this, e);}
    }//GEN-LAST:event_jButton1ActionPerformed

