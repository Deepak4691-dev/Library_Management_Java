  public int calculateFine(Date issueDate, Date returnDate) {
    int allowedDays = 7;
    int finePerDay = 5;

    long diffInMillis = returnDate.getTime() - issueDate.getTime();
    long totalDays = diffInMillis / (1000 * 60 * 60 * 24);

    long lateDays = totalDays - allowedDays;

    if (lateDays > 0) {
        return (int) lateDays * finePerDay;
    } else {
        return 0;
    }
}
