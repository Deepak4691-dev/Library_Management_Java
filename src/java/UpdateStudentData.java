    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
      try{
      Connection deep=DBconnection.getConnection();
         String selectSQL = "SELECT name, course, phone, email FROM students WHERE student_id=?";
PreparedStatement ps = deep.prepareStatement(selectSQL);
ps.setInt(1, Integer.parseInt(jTextField5.getText()));
ResultSet rs = ps.executeQuery();

if (rs.next()) {
    String oldname = rs.getString("name");
    String oldcourse = rs.getString("course");
    String oldphone = rs.getString("phone");
    String oldEmail = rs.getString("email");
    // empty keep old value
    String newname = jTextField1.getText().isEmpty() ? oldname : jTextField1.getText();
    String newcourse = jTextField2.getText().isEmpty() ? oldcourse : jTextField2.getText();
    String newphone = jTextField3.getText().isEmpty() ? oldphone : jTextField3.getText();
    String newemail = jTextField4.getText().isEmpty() ? oldEmail : jTextField4.getText();
    // Updation of values
    String updateSQL = "UPDATE students SET name=?, course=?, phone=?, email=? WHERE student_id=?";
    PreparedStatement p = deep.prepareStatement(updateSQL);

    p.setString(1, newname);
    p.setString(2, newcourse);
    p.setString(3, newphone);
    p.setString(4, newemail);
   p.setInt(5, Integer.parseInt(jTextField5.getText()));
    p.executeUpdate();
    JOptionPane.showMessageDialog(this, "Updated successfully!");
}
      }
      catch(Exception e){e.printStackTrace();JOptionPane.showMessageDialog(this, e.getMessage());}
    }//GEN-LAST:event_jButton1ActionPerformed

