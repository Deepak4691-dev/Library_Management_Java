    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try{
        Connection con = DBconnection.getConnection();

        String title = jTextField1.getText();
        int studentid = Integer.parseInt(jTextField2.getText());

        String checkSql = "SELECT quantity,book_id FROM books WHERE title = ?";
        PreparedStatement checkPst = con.prepareStatement(checkSql);
        checkPst.setString(1, title);
       
        ResultSet rs = checkPst.executeQuery();

         
        if (!rs.next()) {
            JOptionPane.showMessageDialog(this, "❌ Book not found!");
            return;
        }

        int qty = rs.getInt("quantity");

        if (qty <= 0) {
            JOptionPane.showMessageDialog(this, "❌ Book is out of stock!");
            return;
        }
        int idb=rs.getInt("book_id");
        String stus="Issued";

        String issueSql = "INSERT INTO issue_book (book_id, student_id, issue_date, status) VALUES (?, ?, CURDATE(),?)";
        PreparedStatement issuePst = con.prepareStatement(issueSql);
        issuePst.setInt(1, idb);
        issuePst.setInt(2, studentid);
        issuePst.setString(3, stus);
        issuePst.executeUpdate();
        
        String updateSql = "UPDATE books SET quantity = quantity - 1 WHERE title = ?";
        PreparedStatement updatePst = con.prepareStatement(updateSql);
        updatePst.setString(1, title);
        updatePst.executeUpdate();

        JOptionPane.showMessageDialog(this, "✅ Book Issued Successfully!");

        jTextField1.setText("");
        jTextField2.setText("");
        }
        catch(Exception f){f.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error: " + f.getMessage());}
    }//GEN-LAST:event_jButton1ActionPerformed

